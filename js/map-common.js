var muniBorderOverlay = null;

function addMuniBorderOverlay() {
  if (muniBorderOverlay) {
    muniBorderOverlay.bringToFront();
    return;
  }
  fetch(dataUrl("data/municipalities.geojson"))
    .then(function (r) {
      return r.json();
    })
    .then(function (data) {
      // სანამ ფაილი ჩამოვიდოდა, შეიძლება მეორე მოთხოვნამ უკვე შექმნა —
      // მეორე ასლი რუკაზე სამუდამოდ დარჩებოდა (საზღვრები თანდათან მუქდებოდა)
      if (muniBorderOverlay) {
        muniBorderOverlay.bringToFront();
        return;
      }
      muniBorderOverlay = L.geoJSON(data, {
        interactive: false,
        style: {
          fill: false,
          color: MUNI_BORDER_COLOR,
          weight: MUNI_BORDER_WEIGHT,
          opacity: MUNI_BORDER_OPACITY,
          dashArray: MUNI_BORDER_DASH,
        },
      }).addTo(map);
      muniBorderOverlay.bringToFront();
    });
}

function removeMuniBorderOverlay() {
  muniBorderOverlay = clearLayer(muniBorderOverlay);
}

// ===== ფენების რიგითობა: პოლიგონები ქვემოთ → საზღვრები → წერტილები ზემოთ =====
function finalizeLayerOrder() {
  try {
  // თემატურ რუკებზე მუნიც. საზღვრები ყოველთვის ერთნაირად ჩანს
  if (!neutralBoundaryLayer && !muniBorderOverlay) {
    addMuniBorderOverlay();
  }
  var pointLayers = [];
  map.eachLayer(function (l) {
    if (l === muniBorderOverlay || l === natureMuniLayer) return;
    if (l instanceof L.CircleMarker) {
      pointLayers.push(l);
    } else if (l instanceof L.GeoJSON) {
      var hasPoints = false;
      l.eachLayer(function (c) {
        if (c instanceof L.CircleMarker) hasPoints = true;
      });
      if (hasPoints) pointLayers.push(l);
    }
  });
  if (muniBorderOverlay && muniBorderOverlay.bringToFront) {
    muniBorderOverlay.bringToFront();
  }
  // მუნიც. წერტილები საზღვრებზე მაღლა, მაგრამ თემატურ სიმბოლოებზე დაბლა —
  // რომ დიაგრამებმა და პუნსონებმა დაფარონ ისინი
  if (natureMuniLayer && natureMuniLayer.bringToFront) {
    natureMuniLayer.bringToFront();
  }
  pointLayers.forEach(function (l) {
    if (l.bringToFront) l.bringToFront();
  });
  } catch (e) {
    console.warn("layer order:", e);
  }
  restoreInfoBtn();
}

// ინფო-ღილაკი ზოგჯერ ასინქრონული ჩატვირთვის გამო იკარგებოდა — აქ ბრუნდება
function restoreInfoBtn() {
  if (!currentMapInfoKey || !MAP_INFO[currentMapInfoKey]) return;
  var btn = document.getElementById("mapInfoBtn");
  if (!btn) return;
  if (btn.style.display !== "flex" || btn.classList.contains("hidden")) {
    var key = currentMapInfoKey;
    btn.classList.remove("hidden");
    btn.style.display = "flex";
    btn.style.visibility = "visible";
    btn.onclick = function () {
      if (mapInfoVisible) {
        hideMapInfo();
      } else {
        showMapInfo(key);
      }
    };
  }
}

var _layerOrderTimer = null;

function loadNatureMuniCenters() {
  if (natureMuniLayer) return;
  fetch(dataUrl("data/municipalities_centroids.geojson"))
    .then((r) => r.json())
    .then((data) => {
      if (natureMuniLayer) return; // უკვე შექმნა სხვა მოთხოვნამ
      natureMuniLayer = L.geoJSON(data, {
        pointToLayer: function (feature, latlng) {
          var name = feature.properties.Name_Geo || "";
          var marker = L.circleMarker(latlng, {
            radius: 5,
            fillColor: "#4A4035",
            color: "#fff",
            weight: 1.5,
            fillOpacity: 0.9,
          });
          marker.bindTooltip(name, {
            permanent: true,
            direction: "top",
            className: "muni-label",
            offset: [0, -8],
          });
          return marker;
        },
      }).addTo(map);
      addMuniBorderOverlay();
      // წერტილები გვიან ჩამოდის — რიგითობა მაშინვე უნდა გასწორდეს,
      // თორემ თემატურ წერტილოვან ფენას ეფარება (მაგ. ტურიზმის რუკა)
      finalizeLayerOrder();
    });
}

function removeNatureMuniCenters() {
  natureMuniLayer = clearLayer(natureMuniLayer);
  removeMuniBorderOverlay();
}

// დიაგრამიან რუკებზე მუნიც. წერტილები ზედმეტია — საზღვრები რჩება
function hideMuniCenters() {
  natureMuniLayer = clearLayer(natureMuniLayer);
}

function buildAgrovlimatLayer(data) {
  clearLayer(agrovlimatLayer);
  agrovlimatLayer = L.geoJSON(data, {
    style: function (feat) {
      return {
        fillColor: feat.properties.ZoneColor,
        fillOpacity: 0.75,
        color: "#888",
        weight: 0.5,
        opacity: 0.8,
      };
    },
    onEachFeature: function (feature, layer) {
      var p = feature.properties;
      var _tip = p.ZoneLabel || "";
      if (_tip)
        areaTooltip(layer, _tip);
      layer.on("click", function () {
        showInfoAgro(p);
        showBottomChartAgro(p, data);
      });
      layer.on("mouseover", function () {
        layer.setStyle({ weight: 2, fillOpacity: 0.92 });
      });
      layer.on("mouseout", function () {
        agrovlimatLayer.resetStyle(layer);
      });
    },
  }).addTo(map);
  updateAgroLegend(data);
  setInfoBtn("agrovlimat");
}

function loadAgrovlimat() {
  loadData("data/agrovlimat.geojson", function (data) {
    agrovlimatData = data;
    buildAgrovlimatLayer(data);
    loadNatureMuniCenters();
  });
}

