var mapInfoVisible = false;

var mapInfoEl = null;

function showMapInfo(key) {
  var info = MAP_INFO[key];
  if (!info) return;
  if (!mapInfoEl) {
    mapInfoEl = document.createElement("div");
    mapInfoEl.id = "mapInfoPopup";
    document.body.appendChild(mapInfoEl);
  }
  var rows = "";
  if (info.author)
    rows +=
      '<div class="map-info-row"><span class="map-info-label">ავტორი:</span><span>' +
      info.author +
      "</span></div>";
  if (info.cartographer)
    rows +=
      '<div class="map-info-row"><span class="map-info-label">კარტოგ.:</span><span>' +
      info.cartographer +
      "</span></div>";
  if (info.source)
    rows +=
      '<div class="map-info-row"><span class="map-info-label">წყარო:</span><span>' +
      info.source +
      "</span></div>";
  mapInfoEl.innerHTML =
    '<div class="map-info-header"><span class="map-info-title">' +
    info.title +
    "</span>" +
    '<button class="map-info-close" onclick="hideMapInfo()">&#x2715;</button></div>' +
    '<div class="map-info-body">' +
    (info.text
      ? '<p class="map-info-text">' + info.text + "</p>"
      : rows
        ? ""
        : '<p class="map-info-text" style="color:var(--text-muted);font-style:italic;">აღწერა ჯერ არ არის დამატებული.</p>') +
    (rows ? '<div class="map-info-meta">' + rows + "</div>" : "") +
    "</div>";
  mapInfoEl.classList.remove("hidden");
  mapInfoEl.classList.add("visible");
  mapInfoVisible = true;
}

function hideMapInfo() {
  if (mapInfoEl) {
    mapInfoEl.classList.remove("visible");
    mapInfoEl.classList.add("hidden");
  }
  mapInfoVisible = false;
}

var currentMapInfoKey = null;

var _infoBtnTimers = [];

function setInfoBtn(key) {
  hideMapInfo();
  currentMapInfoKey = key && MAP_INFO[key] ? key : null;
  _infoBtnTimers.forEach(clearTimeout);
  _infoBtnTimers = [];
  // ასინქრონული ჩატვირთვები ზოგჯერ ღილაკს აქრობდნენ — რამდენჯერმე ვამოწმებთ
  if (currentMapInfoKey) {
    _infoBtnTimers.push(setTimeout(restoreInfoBtn, 350));
    _infoBtnTimers.push(setTimeout(restoreInfoBtn, 1000));
    _infoBtnTimers.push(setTimeout(restoreInfoBtn, 2200));
  }
  var btn = document.getElementById("mapInfoBtn");
  if (!btn) return;
  if (key && MAP_INFO[key]) {
    btn.classList.remove("hidden");
    btn.style.display = "flex";
    btn.style.visibility = "visible";
    btn.onclick = function () {
      if (mapInfoVisible) {
        hideMapInfo();
      } else {
        showMapInfo(key);
      }
    };
  } else {
    btn.classList.add("hidden");
    btn.style.display = "none";
  }
}

function updateAgroLegend(data) {
  var el = document.getElementById("legendContent");
  if (!el) return;
  var seen = {};
  data.features.forEach(function (f) {
    var p = f.properties;
    if (!seen[p.ZoneKey]) seen[p.ZoneKey] = p.ZoneColor;
  });
  var html = `<div class="section-title">აგროკლიმატური რაიონები</div><div class="ethnics-legend">`;
  AGRO_ZONE_ORDER.forEach(function (key) {
    if (!seen[key]) return;
    html += `<div class="eth-legend-item"><span class="legend-swatch" style="background:${seen[key]};border-color:rgba(0,0,0,0.2);"></span><span style="font-size:10px;">${AGRO_LABELS[key]}</span></div>`;
  });
  html += "</div>";
  el.innerHTML = html;
}

